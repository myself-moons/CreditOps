def fraud_by_category(df: pd.DataFrame) -> list:
    return (
        df.groupby("category")["is_fraud"]
        .agg(["sum", "count", "mean"])
        .reset_index()
        .rename(columns={"sum": "fraud_count", "count": "total", "mean": "fraud_rate"})
        .assign(fraud_rate=lambda x: x["fraud_rate"].round(6))
        .sort_values("fraud_rate", ascending=False)
        .to_dict("records")
    )


def fraud_by_hour(df: pd.DataFrame) -> list:
    df = df.copy()
    df["hour"] = pd.to_datetime(df["trans_date_trans_time"]).dt.hour
    return (
        df.groupby("hour")["is_fraud"]
        .agg(["sum", "count", "mean"])
        .reset_index()
        .rename(columns={"hour": "hour", "sum": "fraud_count", "count": "total", "mean": "fraud_rate"})
        .assign(fraud_rate=lambda x: x["fraud_rate"].round(6))
        .to_dict("records")
    )


def amount_distribution(df: pd.DataFrame) -> dict:
    fraud    = df[df["is_fraud"] == 1]["amt"]
    nonfraud = df[df["is_fraud"] == 0]["amt"]
    def stats(s):
        return {
            "mean": round(float(s.mean()), 2),
            "median": round(float(s.median()), 2),
            "p95": round(float(s.quantile(0.95)), 2),
            "max": round(float(s.max()), 2),
        }
    return {"fraud": stats(fraud), "non_fraud": stats(nonfraud)}


def txn_per_month(df: pd.DataFrame) -> list:
    df = df.copy()
    df["month"] = pd.to_datetime(df["trans_date_trans_time"]).dt.to_period("M")
    return (
        df.groupby("month")
        .agg(total=("is_fraud", "count"), fraud_count=("is_fraud", "sum"))
        .reset_index()
        .assign(
            month=lambda x: x["month"].astype(str),
            fraud_rate=lambda x: (x["fraud_count"] / x["total"]).round(6),
        )
        .to_dict("records")
    )


def sample_rows(df: pd.DataFrame, n: int = 10) -> list:
    """Return a small sample with PII masked."""
    sample = df.sample(min(n, len(df)), random_state=42).copy()
    pii_cols = ["cc_num", "first", "last", "street", "trans_num"]
    for col in pii_cols:
        if col in sample.columns:
            sample[col] = "***masked***"
    safe_cols = [
        "trans_date_trans_time", "category", "amt", "gender",
        "city", "state", "city_pop", "is_fraud",
    ]
    safe_cols = [c for c in safe_cols if c in sample.columns]
    return sample[safe_cols].to_dict("records")


